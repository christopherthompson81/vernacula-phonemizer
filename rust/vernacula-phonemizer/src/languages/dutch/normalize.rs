// generated by .probe/nl/gen_tables.mjs from src/languages/dutch/normalize.ts
const MULTI_DOT: &[(&str, &str)] = &[
    (r"v\.\s?Chr", "voor Christus"),
    (r"n\.\s?Chr", "na Christus"),
    (r"e\.\s?d", "en dergelijke"),
    (r"o\.\s?a", "onder andere"),
    (r"d\.\s?w\.\s?z", "dat wil zeggen"),
    (r"m\.\s?a\.\s?w", "met andere woorden"),
    (r"i\.\s?p\.\s?v", "in plaats van"),
    (r"a\.\s?u\.\s?b", "alstublieft"),
    (r"e\.\s?a", "en andere"),
];
const DOTTED_ABBREV: &[(&str, &str)] = &[
    ("bijv", "bijvoorbeeld"),
    ("bv", "bijvoorbeeld"),
    ("etc", "etcetera"),
    ("enz", "enzovoort"),
    ("ca", "circa"),
    ("dd", "de dato"),
    ("nr", "nummer"),
    ("jr", "junior"),
    ("sr", "senior"),
    ("st", "Sint"),
    ("blz", "bladzijde"),
    ("dr", "dokter"),
    ("prof", "professor"),
    ("ir", "ingenieur"),
    ("drs", "doctorandus"),
    ("mr", "meester"),
    ("mln", "miljoen"),
    ("mld", "miljard"),
];

fn abbrev_word(ab: &JsString) -> Option<&'static str> {
    let k = ab.to_lower_case();
    DOTTED_ABBREV.iter().find(|(a, _)| k == *a).map(|(_, w)| *w)
}

/// `ordinalWord(n)`: below 20 a table lookup; from 20, -ste, except that a sub-20 remainder takes its own
/// small-ordinal form onto the end of the compound.
pub(crate) fn ordinal_word(n: f64) -> Option<JsString> {
    if !is_safe_integer(n) || n < 1.0 {
        return None;
    }
    let below = &MANIFEST.ordinals_below20;
    if n < 20.0 {
        return below.get(n as usize).map(|s| js(s));
    }
    let card = number_to_words(n, None);
    if card.is_empty() || js_re!(r"\d", "u").test(&card) {
        return None;
    }
    let r = (n % 100.0) as usize;
    if (1..20).contains(&r)
        && let Some(tail) = MANIFEST.numbers.ones.get(r)
    {
        let tail = js(tail);
        if card.ends_with(&tail) {
            return Some(
                card.slice(0, Some(-(tail.len() as isize)))
                    .concat(&js(&below[r])),
            );
        }
    }
    Some(card.concat(&js("ste")))
}

/// Step 1's pair of regexes per entry: the marker that ends the string, then anywhere.
static MULTI_DOT_RES: LazyLock<Vec<(JsRegex, JsString, JsRegex, JsString)>> = LazyLock::new(|| {
    MULTI_DOT
        .iter()
        .map(|(body, word)| {
            (
                JsRegex::new(&format!(r"(?<![\p{{L}}\p{{M}}]){body}\.(?=\s*$)"), "giu").unwrap(),
                js(&format!("{word}.")),
                JsRegex::new(&format!(r"(?<![\p{{L}}\p{{M}}]){body}\."), "giu").unwrap(),
                js(word),
            )
        })
        .collect()
});

/// `ABBREV_ALT`: the table's keys, longest first (a stable sort, so equal lengths keep the table's order).
static ABBREV_ALT: LazyLock<String> = LazyLock::new(|| {
    let mut keys: Vec<&str> = DOTTED_ABBREV.iter().map(|(k, _)| *k).collect();
    keys.sort_by_key(|k| std::cmp::Reverse(k.encode_utf16().count()));
    keys.join("|")
});
static ABBREV_CONTINUES: LazyLock<JsRegex> = LazyLock::new(|| {
    JsRegex::new(
        &format!(
            r"(?<![\p{{L}}\p{{M}}])({})\.(\s+)(?=[\p{{L}}\d])",
            *ABBREV_ALT
        ),
        "giu",
    )
    .unwrap()
});
static ABBREV_ENDS: LazyLock<JsRegex> = LazyLock::new(|| {
    JsRegex::new(
        &format!(
            r"(?<![\p{{L}}\p{{M}}])({})\.(?=\s*(?:[.,;:!?»)]|$))",
            *ABBREV_ALT
        ),
        "giu",
    )
    .unwrap()
});

type WordTest = Arc<dyn Fn(&JsString) -> bool + Send + Sync>;

/// `isUnreadableDutch`: the phonotactic test for core/initialisms.ts.
static IS_UNREADABLE: LazyLock<WordTest> = LazyLock::new(|| {
    let p = &MANIFEST.phonotactics;
    Arc::new(make_unreadable_test(PhonotacticsData {
        vowels: JsRegex::new(&format!("[{}]", p.vowels), "u").unwrap(),
        legal_onsets: p.onsets.iter().map(|o| js(o)).collect(),
        legal_codas: p.codas.iter().map(|c| js(c)).collect(),
        liquids: None,
        digraphs: None,
    }))
});

static ACRONYM_LETTERS: LazyLock<HashSet<JsString>> =
    LazyLock::new(|| MANIFEST.acronym_letters.iter().map(|w| js(w)).collect());

fn letter_name(l: &JsString) -> Option<JsString> {
    MANIFEST
        .letter_names
        .get(&l.to_string_lossy())
        .map(|n| js(n))
}

static LETTER_NAME: LazyLock<LetterName> = LazyLock::new(|| Arc::new(letter_name));

/// `isUnreadableDutch(word)`.
pub(crate) fn is_unreadable_dutch(word: &JsString) -> bool {
    IS_UNREADABLE(word)
}

/// `normalizeDutchInitialisms`: nothing is "recorded", so the acronym list and the OOV rule decide.
pub(crate) fn normalize_dutch_initialisms(text: &JsString) -> JsString {
    make_initialism_normalizer(
        InitialismData {
            letter_name: LETTER_NAME.clone(),
            lower: None,
            acronym_letters: Arc::new(|w: &JsString| ACRONYM_LETTERS.contains(w)),
            is_recorded: |_: &JsString| false,
            is_unreadable: IS_UNREADABLE.clone(),
        },
        true,
    )(text)
}

/// `spellCaps(run)`: letter by letter, or `None` if any letter has no name.
fn spell_caps(run: &JsString) -> Option<JsString> {
    let names: Option<Vec<JsString>> = run
        .to_lower_case()
        .code_point_strings()
        .iter()
        .map(letter_name)
        .collect();
    names.map(|n| JsString::join(&n, &js(" ")))
}

/// The clock reading; an existing `uur` is reused rather than appended.
fn clock(h: &JsString, min: &JsString, uur: Option<JsString>) -> JsString {
    let head = number_to_words(js_number(h), Some(h)).concat(&uur.unwrap_or_else(|| js(" uur")));
    if js_number(min) == 0.0 {
        head
    } else {
        head.concat(&js(" "))
            .concat(&number_to_words(js_number(min), Some(min)))
    }
}

/// `normalizeDutch(input)`.
pub(crate) fn normalize_dutch(input: &JsString) -> JsString {
    let mut s = input.clone();

    // 0) the dollar code → the bare sign, before the initialism pass can split it.
    s = rewrite(
        &s,
        js_re!(r"(?<![\p{L}\p{M}])(?:US|AUD)\$(?=[  ]?\d)", "gu"),
        &js("$"),
    );

    // 1) era markers and the multi-dot abbreviations: the final dot kept at the string's end only.
    for (end_re, end_word, re, word) in MULTI_DOT_RES.iter() {
        s = rewrite(&s, end_re, end_word);
        s = rewrite(&s, re, word);
    }

    // 2) dotted capital runs → a bare caps run.
    s = rewrite_with(
        &s,
        js_re!(r"(?<![\p{L}\p{M}])\p{Lu}\.(?:[  ]?\p{Lu}\.)+", "gu"),
        |m, t| js_re!(r"[.\s]", "gu").replace(&m.value(t), &JsString::new()),
    );

    // 3) single-dot abbreviations. ⚠ The miss branch is reachable (#1122): the `iu` fold widens the pattern past
    //    the table's keys, and the match then stays as written.
    s = rewrite_with(&s, &ABBREV_CONTINUES, |m, t| {
        match abbrev_word(&m.group(1, t).unwrap()) {
            None => m.value(t),
            Some(w) => js(w).concat(&m.group(2, t).unwrap()),
        }
    });
    s = rewrite_with(&s, &ABBREV_ENDS, |m, t| {
        match abbrev_word(&m.group(1, t).unwrap()) {
            None => m.value(t),
            Some(w) => js(w).concat(&js(".")),
        }
    });

    // 4) ordinals: a numeral plus a letter suffix.
    s = rewrite_with(
        &s,
        js_re!(
            r"(?<![\d,.])(\d{1,4})(?:ste[n]?|de[n]?|e)(?![\p{L}\p{M}])",
            "gu"
        ),
        |m, t| ordinal_word(js_number(&m.group(1, t).unwrap())).unwrap_or_else(|| m.value(t)),
    );

    // 5) clock, the colon form and then the dot form.
    s = rewrite_with(
        &s,
        js_re!(
            r"(?<![\d:])([01]?\d|2[0-3]):([0-5]\d)(?![:\d])(\s*uur)?",
            "gu"
        ),
        |m, t| {
            clock(
                &m.group(1, t).unwrap(),
                &m.group(2, t).unwrap(),
                m.group(3, t),
            )
        },
    );
    s = rewrite_with(
        &s,
        js_re!(
            r"(?<![\d.,:])([01]?\d|2[0-3])\.([0-5]\d)(?![\d.,:])(\s*uur)?",
            "gu"
        ),
        |m, t| {
            clock(
                &m.group(1, t).unwrap(),
                &m.group(2, t).unwrap(),
                m.group(3, t),
            )
        },
    );

    // 8) degrees.
    s = rewrite(
        &s,
        js_re!(r"(\d)\s?°\s?C(?![\p{L}\p{M}])", "gui"),
        &js("$1 graden Celsius"),
    );
    s = rewrite(
        &s,
        js_re!(r"(\d)\s?°\s?F(?![\p{L}\p{M}])", "gui"),
        &js("$1 graden Fahrenheit"),
    );
    s = rewrite_with(
        &s,
        js_re!(r"(\d)\s?°\s?([NOZW])(?![\p{L}\p{M}])", "gu"),
        |m, t| {
            let dir = match m.group(2, t).unwrap().to_string_lossy().as_str() {
                "N" => "noord",
                "O" => "oost",
                "Z" => "zuid",
                _ => "west",
            };
            m.group(1, t)
                .unwrap()
                .concat(&js(" graden "))
                .concat(&js(dir))
        },
    );
    s = rewrite(&s, js_re!(r"(\d)\s?°", "gu"), &js("$1 graden"));

    // 9) signs.
    s = rewrite(&s, js_re!(r"\+\s?(?=\d)", "gu"), &js(" plus "));
    s = rewrite(&s, js_re!("±", "gu"), &js(" plus min "));
    s = rewrite(&s, js_re!(r"\s?=\s?", "gu"), &js(" is gelijk aan "));
    s = rewrite(&s, js_re!(r"\s?<\s?", "gu"), &js(" kleiner dan "));
    s = rewrite(&s, js_re!(r"\s?>\s?", "gu"), &js(" groter dan "));
    s = rewrite(&s, js_re!(r"\s?÷\s?", "gu"), &js(" gedeeld door "));

    // 10) ampersand: the tight capital form spelled with letter names, the spaced form as *en*.
    s = rewrite_with(
        &s,
        js_re!(r"(?<![\p{L}\p{M}])(\p{Lu})&(\p{Lu})(?![\p{L}\p{M}])", "gu"),
        |m, t| match (
            spell_caps(&m.group(1, t).unwrap()),
            spell_caps(&m.group(2, t).unwrap()),
        ) {
            (Some(x), Some(y)) => x.concat(&js(" en ")).concat(&y),
            _ => m.value(t),
        },
    );
    s = rewrite(&s, js_re!(r"\s&\s", "gu"), &js(" en "));

    // 11) fractions on the ordinal; ½ is *een half*. The two guards are mirrors (#1524, the #1495 family).
    s = rewrite_with(
        &s,
        js_re!(
            r"(?<![\d/]|\d\.|(?<![\d/])\d+,)(\d{1,3})\/(\d{1,3})(?![\d/]|\.\d|,\d+(?![\d/]))",
            "gu"
        ),
        |m, t| {
            let num = js_number(&m.group(1, t).unwrap());
            let den = js_number(&m.group(2, t).unwrap());
            if den == 2.0 {
                return if num == 1.0 {
                    js("een half")
                } else {
                    number_to_words(num, None).concat(&js(" halve"))
                };
            }
            match ordinal_word(den) {
                None => m.value(t),
                Some(ord) => number_to_words(num, None).concat(&js(" ")).concat(&ord),
            }
        },
    );

    s
}
