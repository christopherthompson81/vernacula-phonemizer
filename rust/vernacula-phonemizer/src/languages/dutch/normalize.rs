//! Dutch (nl) text normalization: the dollar code, era and dotted abbreviations, dotted capital runs, letter-suffix
//! ordinals, both clock forms, degrees, signs, the ampersand and fractions rewritten to words; and the initialism
//! pass. Ported from src/languages/dutch/normalize.ts — see that file for the corpus evidence and the ordering.

use std::collections::HashSet;
use std::sync::{Arc, LazyLock};

use super::manifest::MANIFEST;
