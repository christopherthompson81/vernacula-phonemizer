// Replacement for JS `\p{Script=X}` — .NET has no Script properties, only blocks, and blocks are NOT
// scripts (`\p{IsGreek}` misses U+1F00-1FFF polytonic and includes unassigned holes). Every regex in the
// port that used `\p{Script=…}` goes through this class instead.
//
// The tables below are explicit code-point ranges generated from the SAME engine truth the TypeScript
// runs on: Node v22.12.0 (V8 / Unicode 15.1), by testing every code point against /\p{Script=X}/u
// (Script, not Script_Extensions). Generator: a throwaway Node script over 0x0..0x10FFFF; regenerate the
// same way if the fleet ever moves to a Node with a newer Unicode version.
//
// .NET regexes are UTF-16 code-unit based, so astral (non-BMP) ranges cannot sit inside a character
// class — they are emitted as explicit surrogate-pair alternations. `Cls` returns a self-contained
// fragment: "[…]" when the script is BMP-only, "(?:[…]|\uD8xx[\uDCxx-\uDCyy]|…)" when it is not.
// To COMPOSE a script into a larger character class (e.g. JS `[\p{Script=Latin}\p{M}'-]`), use
// `BmpInner` for the class body and OR in `AstralAlt` as an alternation, mirroring what `Cls` does.

